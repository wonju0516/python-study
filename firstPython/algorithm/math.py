# ! 5의 배수면 숫자 대신 Buzz
# ! 3과 5의 배수 둘다면 FizzBuzz

# * 문제의 핵심은 나머지 연산자를 이용하는 것임 만약에 나머지 연산자가 0이면? 분자가 분모의 배수라는 뜻
