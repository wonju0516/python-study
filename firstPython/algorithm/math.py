# * 비트 연산자

# ? bin -> 이진수를 다루기 위한 함수
print(bin(16))

# ? 비트 연산자는 두 개의 이진수로 이루어진 표현식에 사용하는 연산자
# ? AND -> 비트 연산자, 비트 단위로 논리 연산을 수행함
# ? 이진수의 두 비트가 모두 1이면 1을 반환, 그렇지 않으면 0을 반환

# * & (비트 AND) vs and (논리 AND) - 헷갈리기 쉬운 부분
# ! and는 "값 전체"를 참/거짓으로 보고 판단, & 는 "이진수 자릿수(비트) 하나하나"를 따로 비교
# ! 5 and 3 -> 3 (둘 다 참이면 뒤에 있는 값을 그대로 반환, True/False가 아닐 수도 있음)
# ! 5 & 3   -> 1 (자릿수별로 AND: 101 & 011 = 001 = 1)
# ? True/False끼리는 결과가 우연히 같아 보임 (내부적으로 True=1, False=0으로 취급되기 때문)
# ? 하지만 여러 자리 숫자에서는 완전히 다른 결과가 나오므로 "같은 연산자"라고 생각하면 안 됨
# ? and: 조건문에서 논리 판단용 (if a and b:) / &: 특정 비트를 켜고 끄는 저수준 비트 조작용

print(0b10 & 0b11)

print(
    2 & 3
)  # ! 비트 연산자는 반드시 이진수에만 사용하는 것 X! -> 십진수를 이진수로 바꿔 명령을 완료함

# * OR ( | )
# ? 두 비트 중 하나라도 1이면 1을 반환, 둘 다 0일 때만 0
# ? 10 | 11 -> 자리마다 비교: 1|1=1, 0|1=1 -> 결과 11 (3)
print(0b10 | 0b11)

# * XOR ( ^ )
# ? 두 비트가 서로 다르면 1, 같으면 0을 반환 (배타적 OR)
# ? 10 ^ 11 -> 1^1=0, 0^1=1 -> 결과 01 (1)
print(0b10 ^ 0b11)
# ! 같은 값끼리 XOR 하면 항상 0이 됨 (a ^ a == 0), 그래서 "두 값이 같은지" 비교하는 트릭으로도 쓰임

# * NOT ( ~ )
# ? 비트를 전부 반전시킴 (0은 1로, 1은 0으로)
# ! 파이썬 정수는 2의 보수(two's complement) 방식으로 표현되기 때문에, ~n의 결과는 -(n+1)이 됨
print(~5)  # -6  (~n == -(n+1) 이므로 -(5+1))
print(~0)  # -1

# * 왼쪽 시프트 ( << )
# ? 비트를 왼쪽으로 n칸 밀고, 오른쪽에 생긴 빈자리는 0으로 채움
# ! 왼쪽으로 1칸씩 밀 때마다 값이 2배씩 커짐 (2를 곱하는 것과 같은 효과)
print(1 << 2)  # 4   (0001 -> 0100, 1*2*2)
print(3 << 1)  # 6   (0011 -> 0110, 3*2)

# * 오른쪽 시프트 ( >> )
# ? 비트를 오른쪽으로 n칸 밀고, 왼쪽에 생긴 빈자리는 0으로 채움
# ! 오른쪽으로 1칸씩 밀 때마다 값이 절반씩 줄어듦 (2로 나누는 것과 같은 효과, 소수점은 버림)
print(8 >> 2)  # 2   (1000 -> 0010, 8/2/2)
print(7 >> 1)  # 3   (0111 -> 0011, 7//2와 동일한 결과)

# ? 비트 AND 연산자를 사용하면 주어진 숫자가 짝수인지 홀수인지 판단할 수 있다
# ! 0으로 끝나면 짝수, 1로 끝나면 홀수


def is_even(n):
    # * n & 1 -> 이진수 맨 마지막 자리(1의 자리)만 뽑아냄: 0이면 짝수, 1이면 홀수
    # ! &가 not보다 우선순위 높음 -> not n & 1 은 not (n & 1)로 계산됨
    # ? 짝수면 n&1=0 -> not 0 -> True / 홀수면 n&1=1 -> not 1 -> False
    return not n & 1


def is_power(n):
    # * 2의 거듭제곱(1,2,4,8...)은 이진수로 표현하면 1비트가 딱 하나뿐임
    # ! n-1을 하면 그 1비트가 0이 되고 그 아래 자리는 전부 1로 채워짐 (예: 8=1000 -> 7=0111)
    # ? 그래서 n & (n-1)이 0이면 겹치는 비트가 없다는 뜻 -> 2의 거듭제곱
    # ! n=0인 경우는 0 & -1 = 0이 되어 True가 나오는 예외 케이스 (0은 실제로 2의 거듭제곱이 아닌데도 True 반환됨)
    if n & (n - 1) == 0:
        return True
    return False


# * 피즈버즈 (FizzBuzz)
# ? 1부터 어떤 숫자까지 순서대로 출력하는데 (아래 조건들은 제외한것들은 그냥 숫자 그대로 출력)
